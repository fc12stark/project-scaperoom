package edu.estudiantat.upc.EETACEscape;

public class Item {
    private String id;
    private String nom;
    private String descripcio;
    private int preu;
    private String tipus;

    public Item() {
    }

    public String getId() {
        return id;
    }

    public String getNom() {
        return nom;
    }

    public String getDescripcio() {
        return descripcio;
    }

    public int getPreu() {
        return preu;
    }

    public String getTipus() {
        return tipus;
    }
}
